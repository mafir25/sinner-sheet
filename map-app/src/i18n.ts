export function tr(ru: string, ...args: (string | number)[]): string {
  const s = lang === 'en' ? (EN[ru] ?? ru) : ru;
  return args.length ? s.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? '')) : s;
}

/** Имя из набора { ru, en } на текущем языке. */
export const nm = (n: { ru: string; en: string } | undefined, fallback = '') => (n ? n[lang] || n.ru : fallback);
